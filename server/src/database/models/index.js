'use strict';

const fs = require('fs');
const path = require('path');
const Sequelize = require('sequelize');
const process = require('process');
const basename = path.basename(__filename);
const env = process.env.NODE_ENV || 'development';
const config = require(__dirname + '/../../config/config.js')[env];
const db = {};

let sequelize;
if (config.use_env_variable) {
  sequelize = new Sequelize(process.env[config.use_env_variable], config);
} else {
  sequelize = new Sequelize(config.database, config.username, config.password, config);
}

fs
  .readdirSync(__dirname)
  .filter(file => {
    return (
      file.indexOf('.') !== 0 &&
      file !== basename &&
      file.slice(-3) === '.js' &&
      file.indexOf('.test.js') === -1
    );
  })
  .forEach(file => {
    const model = require(path.join(__dirname, file))(sequelize, Sequelize.DataTypes);
    db[model.name] = model;
  });

Object.keys(db).forEach(modelName => {
  if (db[modelName].associate) {
    db[modelName].associate(db);
  }
});

db.sequelize = sequelize;
db.Sequelize = Sequelize;

// Verify the database connection on startup.
// If this fails, the app cannot function correctly, so we log a clear,
// actionable message and terminate the process rather than letting the
// server run in a broken state.
sequelize.authenticate()
  .then(() => {
    console.log(`[Database] Connected successfully to "${config.database}" on ${config.host}:${config.port} (${env} environment).`);
  })
  .catch((err) => {
    console.error(`[Database] Connection failed for "${config.database}" on ${config.host}:${config.port}.`);
    console.error(`[Database] Reason: ${err.message}`);
    console.error('[Database] Check that MySQL/XAMPP is running and .env credentials are correct.');
    process.exit(1);
  });

module.exports = db;
